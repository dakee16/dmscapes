  await db.exec(purchaseMigration); await db.exec(purchaseMigration);
  const first=await create(owner,'Our room'), second=await create(owner,'Another room'), personal=await create(free,'Free room');
  equal((await act(free,personal.id,'share',{enabled:true})).status,403,'Only Pro hosts shared rooms');
  equal((await act(owner,first.id,'share',{enabled:true})).ok,true,'Pro can share');
