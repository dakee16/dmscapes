  equal((await invite(first.id,1,'self')).status,409,'Owner already belongs to room');
  await invite(first.id,3,'first');
  equal((await join(outsider,'first')).status,403,'Forwarded invitation cannot be used by another email');
  await db.query('update auth.users set email_confirmed_at=null where id=$1',[editor]);
  equal((await join(editor,'first')).status,403,'Unverified email cannot accept invitation');
  await db.query('update auth.users set email_confirmed_at=now() where id=$1',[editor]);
